package com.synthesis.service

import com.synthesis.domain.model.exoplanet.LiveTransitTarget
import javax.inject.Inject
import javax.inject.Singleton

@Singleton
class TelescopeExportService @Inject constructor() {

    fun exportToNinaCsv(target: LiveTransitTarget): String {
        return buildString {
            appendLine("# N.I.N.A. Target List - Generated by SYNTHESIS Autonomous Engine")
            appendLine("TargetName,RA_Hours,Dec_Deg,Epoch,TransitDepthPpm,EstimatedDurationHours,Constellation")
            appendLine("${target.candidateName.replace(",", " ")},${target.rightAscension},${target.declination},J2000,${target.transitDepthPpm},${target.transitDurationHours},${target.constellation}")
        }
    }

    fun exportToStellariumJson(target: LiveTransitTarget): String {
        return """
        {
          "version": "1.0",
          "shortName": "SYNTHESIS_Exoplanet_Targets",
          "name": "SYNTHESIS High-Priority Exoplanet Transits",
          "description": "Validated unvetted and mono-transit targets for ground telescope confirmation.",
          "targets": [
            {
              "name": "${target.candidateName}",
              "type": "Exoplanet System",
              "ra": "${target.rightAscension}",
              "dec": "${target.declination}",
              "constellation": "${target.constellation}",
              "magnitude": ${target.apparentVisualMag},
              "transitDepthPpm": ${target.transitDepthPpm},
              "periodDays": ${target.periodDays},
              "nextTransitBtjd": ${target.nextTransitEpochBtjd}
            }
          ]
        }
        """.trimIndent()
    }

    fun exportToAstroImageJ(target: LiveTransitTarget): String {
        return buildString {
            appendLine("# AstroImageJ (AIJ) Transit Photometry Observation Log")
            appendLine("# Target: ${target.candidateName} (TIC ${target.ticId})")
            appendLine("# Constellation: ${target.constellation} | V-Mag: ${target.apparentVisualMag}")
            appendLine("# Period: ${target.periodDays} days | Duration: ${target.transitDurationHours} hours")
            appendLine("# Predicted Ingress Epoch: BTJD ${String.format("%.4f", target.nextTransitEpochBtjd)}")
            appendLine("# Expected Depth: ${target.transitDepthPpm} ppm (${String.format("%.4f", target.transitDepthPpm / 10000.0)} %)")
            appendLine("TIME_BJD_TDB\tFLUX_REL\tERROR\tAIRMASS\tAPERTURE_RADIUS_PX")
            appendLine("# Recommended Aperture: 8 to 14 pixels based on FWHM seeing.")
        }
    }
}
